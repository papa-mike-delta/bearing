import { readFile, writeFile } from "node:fs/promises";

export async function skillsModuleSource() {
  const files = ["weekly-review", "habit-design"];
  const entries = await Promise.all(files.map(async (name) => [name, await readFile(new URL(`../skills/${name}.md`, import.meta.url), "utf8")]));
  return `// Generated by scripts/generate-skills.ts from skills/*.md. Do not edit.\nexport const skillFiles: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`;
}
if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(new URL("../src/skills.generated.ts", import.meta.url), await skillsModuleSource());
}
