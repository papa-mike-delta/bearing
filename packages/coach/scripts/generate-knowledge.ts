// Embeds knowledge/*.md into src/knowledge-articles.generated.ts, so the
// articles ship inside the server bundle instead of being read from disk at
// runtime (Vercel does not trace files read with node:fs). Run after editing
// a knowledge article: node scripts/generate-knowledge.ts
import { readFile, writeFile } from "node:fs/promises";
import { URL } from "node:url";

export async function knowledgeModuleSource() {
  const read = (name: string) => readFile(new URL(`../knowledge/${name}`, import.meta.url), "utf8");
  const [habits, journaling, people, notes] = await Promise.all([read("habits.md"), read("journaling.md"), read("people.md"), read("notes.md")]);
  return `// Generated by scripts/generate-knowledge.ts from knowledge/*.md. Do not edit.\n\nexport const habitsMarkdown = ${JSON.stringify(habits)};\n\nexport const journalingMarkdown = ${JSON.stringify(journaling)};\n\nexport const peopleMarkdown = ${JSON.stringify(people)};\n\nexport const notesMarkdown = ${JSON.stringify(notes)};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(new URL("../src/knowledge-articles.generated.ts", import.meta.url), await knowledgeModuleSource());
}
